package com.sdprep.ecommerce.core;

import com.sdprep.ecommerce.core.Order.OrderLine;

import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicLong;

/**
 * Turns a cart into an order. A small saga with a compensating step:
 * <ol>
 *   <li>reserve stock (all-or-nothing)</li>
 *   <li>charge the customer</li>
 *   <li>success → commit stock, clear cart; failure → release stock (compensation), keep cart</li>
 * </ol>
 */
public class CheckoutService {

    private final Catalog catalog;
    private final Inventory inventory;
    private final CartService carts;
    private final PaymentGateway payments;
    private final Map<String, Order> ordersById = new ConcurrentHashMap<>();
    private final Map<String, Order> ordersByIdempotencyKey = new ConcurrentHashMap<>();
    private final AtomicLong nextOrderId = new AtomicLong(1);

    public CheckoutService(Catalog catalog, Inventory inventory, CartService carts, PaymentGateway payments) {
        this.catalog = catalog;
        this.inventory = inventory;
        this.carts = carts;
        this.payments = payments;
    }

    /**
     * @param idempotencyKey generated by the client per checkout attempt; a double-click or retry with the
     *                       same key returns the first result instead of placing a second order
     */
    public Order checkout(String userId, String idempotencyKey) {
        // computeIfAbsent runs placeOrder at most once per key, even for concurrent retries.
        // If placeOrder throws (e.g. out of stock), nothing is stored and the client may retry.
        // Production: a unique constraint on the idempotency key in the orders table.
        return ordersByIdempotencyKey.computeIfAbsent(idempotencyKey, key -> placeOrder(userId));
    }

    public Optional<Order> find(String orderId) {
        return Optional.ofNullable(ordersById.get(orderId));
    }

    private Order placeOrder(String userId) {
        Map<String, Integer> cart = carts.view(userId);
        if (cart.isEmpty()) {
            throw new InvalidRequestException("Cart is empty");
        }
        List<OrderLine> lines = cart.entrySet().stream()
                .map(item -> {
                    Product product = catalog.get(item.getKey());
                    return new OrderLine(product.id(), product.name(), item.getValue(), product.priceCents());
                })
                .toList();
        long total = lines.stream().mapToLong(line -> line.unitPriceCents() * line.quantity()).sum();

        inventory.reserve(cart); // throws OutOfStockException with nothing reserved
        String orderId = "ord-" + nextOrderId.getAndIncrement();
        boolean charged = payments.charge(userId, total, orderId);

        Order order;
        if (charged) {
            inventory.commit(cart);
            carts.clear(userId);
            order = new Order(orderId, userId, lines, total, Order.Status.PAID);
        } else {
            inventory.release(cart); // compensate: put the stock back
            order = new Order(orderId, userId, lines, total, Order.Status.PAYMENT_FAILED);
        }
        ordersById.put(orderId, order);
        return order;
    }
}
